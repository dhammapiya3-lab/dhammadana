"""『불자수첩』(DL-0033) 글로 읽기 본문 만들기.
PDF 에 글자층이 없어(글자가 모두 그림 선) 쪽마다 그림으로 보고 옮겨 적은 원고(쪽마다 NNN.md)를 모음.
쓰는 법: python3 tools/build_dl0033.py tools/dl0033  → content/texts/DL-0033.json
원고(tools/dl0033/NNN.md, 쪽마다 하나)를 고치고 다시 돌림.
"""
import json, os, re, sys
src = sys.argv[1]
pages = []
for n in range(1, 176):
    t = open(os.path.join(src, f'{n:03d}.md')).read().strip()
    lab = '' if n <= 2 else f'{n}쪽'
    pages.append((lab, t))
body = '\n\n'.join(f'=== {lab} ===\n{t}' if lab else f'=== ===\n{t}' for lab, t in pages)

TOC = [  # (제목, 쪽, 아랫단계)
 ('속표지', 1, 0), ('발원문', 2, 0), ('부처님의 마지막 유언', 3, 0), ('선원소개', 4, 0), ('프로그램 안내', 5, 0), ('목차', 6, 0),
 ('수행자 지침', 7, 0), ('삼보예경', 16, 0), ('부처님찬탄게송', 18, 0),
 ('청법', 19, 0), ('오계를 청함', 20, 0), ('팔계를 청함', 23, 0), ('삼보에 귀의', 27, 0), ('오계 수지', 31, 0), ('수계공덕 발원', 33, 1), ('수계스승 훈계', 34, 1),
 ('팔계 수지', 35, 0), ('수계공덕 발원', 38, 1), ('수계스승 훈계', 39, 1),
 ('부처님의 공덕', 40, 0), ('법의 공덕', 41, 1), ('상가의 공덕', 42, 1),
 ('네 가지 필수품에 대한 숙고', 44, 0), ('1. 가사에 대한 숙고', 44, 1), ('2. 음식에 대한 숙고', 46, 1), ('3. 거처에 대한 숙고', 48, 1), ('4. 약품에 대한 숙고', 49, 1),
 ('오-와-다 빠-띠목카', 50, 0), ('다섯 가지 공양올림', 52, 0), ('부처님의 깨달음 게송', 57, 0), ('십이연기의 법', 59, 0), ('조건의 개요', 73, 0), ('성불 찬탄게송', 75, 0),
 ('공덕회향', 78, 0), ('발원회향', 80, 1), ('자애관', 82, 0), ('연민관', 85, 0), ('참회예경', 86, 0), ('죽음관', 88, 0), ('기원', 90, 0), ('대예경', 91, 0),
 ('사무량심', 109, 0), ('축원', 116, 1), ('회향', 118, 1),
 ('경전', 121, 0), ('천신들 초청게송', 122, 0), ('보호경', 123, 0), ('축복경', 127, 0), ('보배경', 141, 0), ('자애경', 158, 0), ('몸의 보호경(무더기경)', 168, 0),
 ('법보시 회향문', 174, 0), ('판권지', 175, 0),
]
toc = []
for t, p, s in TOC:
    e = {'title': t, 'page': p, 'sub': bool(s)}
    if s:  # 아랫단계는 쪽 안의 소제목 자리(at)
        paras = pages[p - 1][1].split('\n\n')
        k = next((i for i, q in enumerate(paras) if q.startswith('## ') and q[3:].strip() == t), None)
        if k: e['at'] = k
    toc.append(e)
out = {'book': 'DL-0033', 'edition': '초판', 'toc': toc, 'images': [], 'body': body}
json.dump(out, open(os.path.join(os.path.dirname(__file__), '..', 'content', 'texts', 'DL-0033.json'), 'w'), ensure_ascii=False, indent=1)
print('쪽', len(pages), '목차', len(toc), '글자', len(body))
